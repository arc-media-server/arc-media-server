package main

import (
	"context"
	"database/sql"
	"fmt"
	"strings"
)

const postgresFunctions = `
CREATE FUNCTION arc_lower(text) RETURNS text LANGUAGE SQL IMMUTABLE STRICT PARALLEL SAFE AS $arc$
 SELECT translate($1,'ABCDEFGHIJKLMNOPQRSTUVWXYZ','abcdefghijklmnopqrstuvwxyz')
$arc$;
`

type schemaColumn struct {
	name, kind  string
	notnull, pk int
	def         sql.NullString
}

func sqliteColumns(ctx context.Context, db *sql.DB, table string) ([]schemaColumn, error) {
	rows, err := db.QueryContext(ctx, "PRAGMA table_xinfo("+quoted(table)+")")
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []schemaColumn
	for rows.Next() {
		var c schemaColumn
		var cid, hidden int
		if err = rows.Scan(&cid, &c.name, &c.kind, &c.notnull, &c.def, &c.pk, &hidden); err != nil {
			return nil, err
		}
		if hidden != 0 {
			return nil, fmt.Errorf("generated or hidden column needs explicit PostgreSQL port: %s.%s", table, c.name)
		}
		out = append(out, c)
	}
	return out, rows.Err()
}
func postgresBaseline(ctx context.Context, db *sql.DB) (string, error) {
	rows, err := db.QueryContext(ctx, "SELECT type,name,sql FROM sqlite_schema WHERE type<>'index' AND name NOT GLOB 'sqlite_*' ORDER BY name")
	if err != nil {
		return "", err
	}
	ddl := map[string]string{}
	var names []string
	for rows.Next() {
		var kind, n, q string
		if err = rows.Scan(&kind, &n, &q); err != nil {
			rows.Close()
			return "", err
		}
		if kind != "table" || strings.HasPrefix(strings.ToUpper(q), "CREATE VIRTUAL TABLE") {
			rows.Close()
			return "", fmt.Errorf("SQLite %s needs explicit PostgreSQL port: %s", kind, n)
		}
		names = append(names, n)
		ddl[n] = q
	}
	err = rows.Err()
	rows.Close()
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("-- Generated by go run ./tools/dbschema.\n" + postgresFunctions)
	var extras []string
	for _, table := range names {
		cols, err := sqliteColumns(ctx, db, table)
		if err != nil {
			return "", err
		}
		var definitions []string
		pk := map[int]string{}
		nPK := 0
		for _, c := range cols {
			if c.pk > 0 {
				nPK++
				pk[c.pk] = c.name
			}
		}
		for _, c := range cols {
			typ := strings.ToUpper(c.kind)
			switch typ {
			case "INTEGER":
				typ = "BIGINT"
			case "REAL":
				typ = "DOUBLE PRECISION"
			case "TEXT":
				typ = `TEXT COLLATE "C"`
			case "BLOB":
				typ = "BYTEA"
			default:
				return "", fmt.Errorf("unsupported schema type %s.%s", table, c.name)
			}
			def := quoted(c.name) + " " + typ
			if c.pk > 0 && nPK == 1 && typ == "BIGINT" && !strings.Contains(strings.ToUpper(ddl[table]), "WITHOUT ROWID") {
				def += " GENERATED BY DEFAULT AS IDENTITY"
			}
			if c.notnull != 0 || c.pk > 0 {
				def += " NOT NULL"
			}
			if c.def.Valid {
				def += " DEFAULT " + c.def.String
			}
			definitions = append(definitions, def)
		}
		if nPK > 0 {
			var p []string
			for i := 1; i <= nPK; i++ {
				p = append(p, quoted(pk[i]))
			}
			definitions = append(definitions, "PRIMARY KEY ("+strings.Join(p, ",")+")")
		}
		for _, check := range schemaChecks(ddl[table]) {
			definitions = append(definitions, "CHECK "+check)
		}
		if hasSQLiteRowIDQueries(table) {
			definitions = append(definitions, `arc_rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE`)
		}
		b.WriteString("CREATE TABLE " + quoted(table) + " (\n " + strings.Join(definitions, ",\n ") + "\n);\n")
		// Reconstruct every explicit/unique index, preserving column order, descending flags,
		// partial predicates and ASCII-only NOCASE expression uniqueness.
		ir, err := db.QueryContext(ctx, "PRAGMA index_list("+quoted(table)+")")
		if err != nil {
			return "", err
		}
		type idx struct {
			name, origin    string
			unique, partial int
		}
		var indices []idx
		for ir.Next() {
			var x idx
			var seq int
			if err = ir.Scan(&seq, &x.name, &x.unique, &x.origin, &x.partial); err != nil {
				ir.Close()
				return "", err
			}
			if x.origin != "pk" {
				indices = append(indices, x)
			}
		}
		err = ir.Err()
		ir.Close()
		if err != nil {
			return "", err
		}
		for n, x := range indices {
			xr, err := db.QueryContext(ctx, "PRAGMA index_xinfo("+quoted(x.name)+")")
			if err != nil {
				return "", err
			}
			var fields []string
			for xr.Next() {
				var seq, cid, desc, key int
				var name, coll sql.NullString
				if err = xr.Scan(&seq, &cid, &name, &desc, &coll, &key); err != nil {
					xr.Close()
					return "", err
				}
				if key == 0 {
					continue
				}
				if !name.Valid {
					xr.Close()
					return "", fmt.Errorf("expression index needs explicit PostgreSQL port: %s", x.name)
				}
				f := quoted(name.String)
				if coll.String == "NOCASE" {
					f = "arc_lower(" + f + ")"
				}
				if desc != 0 {
					f += " DESC"
				}
				fields = append(fields, f)
			}
			err = xr.Err()
			xr.Close()
			if err != nil {
				return "", err
			}
			prefix := "CREATE "
			if x.unique != 0 {
				prefix += "UNIQUE "
			}
			name := x.name
			if x.origin == "u" {
				name = fmt.Sprintf("arc_%s_unique_%d", table, n)
			}
			q := prefix + "INDEX " + quoted(name) + " ON " + quoted(table) + " (" + strings.Join(fields, ",") + ")"
			if x.partial != 0 {
				var orig string
				if err = db.QueryRowContext(ctx, "SELECT sql FROM sqlite_schema WHERE name=?", x.name).Scan(&orig); err != nil {
					return "", err
				}
				at := strings.Index(strings.ToUpper(orig), " WHERE ")
				if at < 0 {
					return "", fmt.Errorf("missing partial predicate: %s", x.name)
				}
				q += orig[at:]
			}
			extras = append(extras, q+";")
		}
		// SQLite NOCASE primary-key columns need the same folded uniqueness as unique indexes.
		if table == "item_labels" {
			extras = append(extras, `CREATE UNIQUE INDEX item_labels_folded ON item_labels(item_id,arc_lower(label));`)
		}
		fr, err := db.QueryContext(ctx, "PRAGMA foreign_key_list("+quoted(table)+")")
		if err != nil {
			return "", err
		}
		for fr.Next() {
			var id, seq int
			var target, from, to, onUpdate, onDelete, match string
			if err = fr.Scan(&id, &seq, &target, &from, &to, &onUpdate, &onDelete, &match); err != nil {
				fr.Close()
				return "", err
			}
			if seq != 0 {
				fr.Close()
				return "", fmt.Errorf("composite FK needs explicit port: %s", table)
			}
			extras = append(extras, fmt.Sprintf("ALTER TABLE %s ADD CONSTRAINT %s FOREIGN KEY (%s) REFERENCES %s(%s) ON UPDATE %s ON DELETE %s DEFERRABLE INITIALLY DEFERRED;", quoted(table), quoted(fmt.Sprintf("arc_%s_fk_%d", table, id)), quoted(from), quoted(target), quoted(to), onUpdate, onDelete))
		}
		err = fr.Err()
		fr.Close()
		if err != nil {
			return "", err
		}
	}
	for _, q := range extras {
		b.WriteString(q + "\n")
	}
	return b.String(), nil
}

// These tables use rowid in shared catalog queries. Give PostgreSQL an equivalent identity.
func hasSQLiteRowIDQueries(table string) bool {
	return table == "items" || table == "item_genres" || table == "item_labels"
}
func schemaChecks(q string) []string {
	t := significantSQL(q)
	var out []string
	for i := 0; i < len(t); i++ {
		if strings.EqualFold(t[i], "CHECK") && i+1 < len(t) && t[i+1] == "(" {
			end := closingSQL(t, i+1)
			if end > i {
				out = append(out, strings.Join(t[i+1:end+1], " "))
				i = end
			}
		}
	}
	return out
}

// sqlTokens keeps quoted strings and identifiers intact while finding CHECK clauses.
func sqlTokens(q string) []string {
	var out []string
	for i := 0; i < len(q); {
		start := i
		c := q[i]
		i++
		switch {
		case c == '\'' || c == '"' || c == '`':
			for i < len(q) {
				if q[i] == c {
					i++
					if i < len(q) && q[i] == c {
						i++
						continue
					}
					break
				}
				i++
			}
		case c == '-' && i < len(q) && q[i] == '-':
			for i < len(q) && q[i] != '\n' {
				i++
			}
		case c == '/' && i < len(q) && q[i] == '*':
			i++
			for i+1 < len(q) && q[i:i+2] != "*/" {
				i++
			}
			if i+1 < len(q) {
				i += 2
			}
		case i < len(q) && ((c == '<' && (q[i] == '>' || q[i] == '=')) || (c == '>' && q[i] == '=') || (c == '|' && q[i] == '|') || (c == ':' && q[i] == ':')):
			i++
		case c == '?':
			for i < len(q) && q[i] >= '0' && q[i] <= '9' {
				i++
			}
		case c == ' ' || c == '\n' || c == '\t' || c == '\r':
			for i < len(q) && strings.ContainsRune(" \n\t\r", rune(q[i])) {
				i++
			}
		case c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c == '_' || c >= '0' && c <= '9':
			for i < len(q) {
				v := q[i]
				if !(v >= 'a' && v <= 'z' || v >= 'A' && v <= 'Z' || v == '_' || v >= '0' && v <= '9') {
					break
				}
				i++
			}
		}
		out = append(out, q[start:i])
	}
	return out
}

func significantSQL(q string) []string {
	var out []string
	for _, t := range sqlTokens(q) {
		if strings.TrimSpace(t) == "" || strings.HasPrefix(t, "--") || strings.HasPrefix(t, "/*") {
			continue
		}
		out = append(out, t)
	}
	return out
}

func closingSQL(t []string, start int) int {
	depth := 0
	for i := start; i < len(t); i++ {
		if t[i] == "(" {
			depth++
		}
		if t[i] == ")" {
			depth--
			if depth == 0 {
				return i
			}
		}
	}
	return -1
}

func quoted(s string) string { return `"` + strings.ReplaceAll(s, `"`, `""`) + `"` }
