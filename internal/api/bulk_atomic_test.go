package api

import (
	"context"
	"database/sql"
	"fmt"
	"net/http/httptest"
	"path/filepath"
	"strings"
	"testing"

	"ams/internal/store"
)

func TestBulkWatchFailureDoesNotCommitMetadataOrEarlierWatchState(t *testing.T) {
	path := filepath.Join(t.TempDir(), "test.db")
	s, u := securityServerAt(t, path)
	ctx := t.Context()
	lib, err := s.store.SyncLibrary(ctx, "Movies", "movies", "tmdb_aired", nil)
	if err != nil {
		t.Fatal(err)
	}
	var ids []string
	for _, name := range []string{"First", "Second"} {
		id, _, err := s.store.EnsureItem(ctx, &store.Item{LibraryID: lib, Kind: "movie", Title: name}, name)
		if err != nil {
			t.Fatal(err)
		}
		ids = append(ids, id)
		if err := s.store.SetWatchlist(ctx, u.ID, id, true); err != nil {
			t.Fatal(err)
		}
	}
	// Reject only the later title's watch update, after the request has validated.
	// IDs are generated by the fixture, not untrusted SQL inputs.
	trigger := fmt.Sprintf(`CREATE TRIGGER reject_later_watch BEFORE UPDATE OF played ON user_item_data WHEN NEW.item_id='%s' BEGIN SELECT RAISE(ABORT,'fixture watch write refused'); END`, ids[1])
	db, err := sql.Open("sqlite", path)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	if _, err := db.ExecContext(ctx, trigger); err != nil {
		t.Fatal(err)
	}
	body := fmt.Sprintf(`{"item_ids":["%s","%s"],"add_labels":["Changed"],"content_rating":"18","played":true}`, ids[0], ids[1])
	r := httptest.NewRequest("POST", "/api/v1/items/bulk", strings.NewReader(body))
	r = r.WithContext(context.WithValue(r.Context(), userKey, u))
	w := httptest.NewRecorder()
	s.editItems(w, r)
	if w.Code != 500 {
		t.Fatalf("want write failure, got %d %s", w.Code, w.Body.String())
	}
	for _, id := range ids {
		it, err := s.store.GetItem(ctx, id)
		if err != nil {
			t.Fatal(err)
		}
		labels, err := s.store.ItemLabels(ctx, id)
		if err != nil {
			t.Fatal(err)
		}
		if len(labels) != 0 || it.ContentRating != "" || len(it.LockedFields) != 0 {
			t.Errorf("failed bulk committed metadata: labels=%v rating=%q locks=%v", labels, it.ContentRating, it.LockedFields)
		}
	}
	data, err := s.store.UserDataFor(ctx, u.ID, ids)
	if err != nil {
		t.Fatal(err)
	}
	for _, id := range ids {
		if data[id].Played || !data[id].Watchlisted {
			t.Errorf("failed bulk committed watch state: %+v", data[id])
		}
	}
	// A retry after the transient failure applies everything together exactly once.
	if _, err := db.ExecContext(ctx, "DROP TRIGGER reject_later_watch"); err != nil {
		t.Fatal(err)
	}
	r = httptest.NewRequest("POST", "/api/v1/items/bulk", strings.NewReader(body))
	r = r.WithContext(context.WithValue(r.Context(), userKey, u))
	w = httptest.NewRecorder()
	s.editItems(w, r)
	if w.Code != 204 {
		t.Fatalf("retry: %d %s", w.Code, w.Body.String())
	}
	data, err = s.store.UserDataFor(ctx, u.ID, ids)
	if err != nil {
		t.Fatal(err)
	}
	for _, id := range ids {
		it, err := s.store.GetItem(ctx, id)
		if err != nil {
			t.Fatal(err)
		}
		labels, err := s.store.ItemLabels(ctx, id)
		if err != nil {
			t.Fatal(err)
		}
		var minAge int
		if err := db.QueryRowContext(ctx, "SELECT min_age FROM items WHERE id = ?", id).Scan(&minAge); err != nil {
			t.Fatal(err)
		}
		if it.ContentRating != "18" || minAge != 18 || len(labels) != 1 || labels[0] != "Changed" || !data[id].Played || data[id].PlayCount != 1 || data[id].Watchlisted {
			t.Errorf("retry did not apply complete update: item=%+v labels=%v state=%+v", it, labels, data[id])
		}
	}

}
