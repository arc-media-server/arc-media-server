package apidoc

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

// The v1 promise (docs/API.md, Versions): endpoints and the fields they answer with aren't removed
// or changed incompatibly; new ones may appear. docs/api-v1-contract.txt lists every endpoint,
// success status and response field (with its JSON type) that apps may rely on. The generator
// only ever adds to it, so removing or retyping something fails TestV1ContractKept until the
// line is deleted from the file by hand, which makes the break visible in review.

const contractFile = "api-v1-contract.txt"

// contractLines flattens an OpenAPI document into sorted lines such as
// "GET /items/{id} 200 .title string".
func contractLines(openapi []byte) ([]string, error) {
	var doc struct {
		Paths      map[string]map[string]json.RawMessage `json:"paths"`
		Components struct {
			Schemas map[string]map[string]any `json:"schemas"`
		} `json:"components"`
	}
	if err := json.Unmarshal(openapi, &doc); err != nil {
		return nil, err
	}
	seen := map[string]bool{}
	add := func(s string) { seen[s] = true }
	var walk func(prefix, path string, schema map[string]any, refs []string)
	var visit func(prefix, path string, schema map[string]any, refs []string, emit bool)
	walk = func(prefix, path string, schema map[string]any, refs []string) {
		visit(prefix, path, schema, refs, true)
	}
	visit = func(prefix, path string, schema map[string]any, refs []string, emit bool) {
		if ref, ok := schema["$ref"].(string); ok {
			name := strings.TrimPrefix(ref, "#/components/schemas/")
			if slices.Contains(refs, name) || len(refs) > 6 {
				return // recursive types are covered at their first level
			}
			if target, ok := doc.Components.Schemas[name]; ok {
				visit(prefix, path, target, append(refs, name), emit)
			}
			return
		}
		if alternatives, ok := schema["anyOf"].([]any); ok {
			if path != "" && emit {
				kinds := schemaKinds(schema, doc.Components.Schemas, nil)
				add(fmt.Sprintf("%s %s %s", prefix, path, strings.Join(kinds, "|")))
				// Keep existing single-type promises when an already valid nullable
				// alternative is documented. Protect the complete union and each
				// alternative too: narrowing or retyping still removes a promise.
				for _, kind := range kinds {
					add(fmt.Sprintf("%s %s %s", prefix, path, kind))
				}
			}
			for _, alternative := range alternatives {
				if sub, ok := alternative.(map[string]any); ok {
					visit(prefix, path, sub, refs, false)
				}
			}
			return
		}
		typ, _ := schema["type"].(string)
		if path != "" && emit {
			add(fmt.Sprintf("%s %s %s", prefix, path, cmpType(typ)))
		}
		switch typ {
		case "array":
			if items, ok := schema["items"].(map[string]any); ok {
				walk(prefix, path+"[]", items, refs)
			}
		default:
			if value, ok := schema["additionalProperties"].(map[string]any); ok && len(value) > 0 {
				walk(prefix, path+"{}", value, refs)
			}
			props, _ := schema["properties"].(map[string]any)
			for name, p := range props {
				if ps, ok := p.(map[string]any); ok {
					walk(prefix, path+"."+name, ps, refs)
				}
			}
		}
	}
	for path, methods := range doc.Paths {
		for method, raw := range methods {
			var op struct {
				Responses map[string]struct {
					Content map[string]struct {
						Schema map[string]any `json:"schema"`
					} `json:"content"`
				} `json:"responses"`
			}
			if err := json.Unmarshal(raw, &op); err != nil || op.Responses == nil {
				continue
			}
			endpoint := strings.ToUpper(method) + " " + path
			add(endpoint)
			for status, resp := range op.Responses {
				if !strings.HasPrefix(status, "2") {
					continue
				}
				prefix := endpoint + " " + status
				add(prefix)
				if c, ok := resp.Content["application/json"]; ok && c.Schema != nil {
					walk(prefix, "", c.Schema, nil)
				}
			}
		}
	}
	lines := make([]string, 0, len(seen))
	for l := range seen {
		lines = append(lines, l)
	}
	slices.Sort(lines)
	return lines, nil
}

// cmpType names a field's type for the contract; an untyped (free-form) value is "any".
func cmpType(t string) string {
	if t == "" {
		return "any"
	}
	return t
}

// contract returns the recorded v1 contract and what the code answers with now.
func contract(root string) (recorded, current []string, err error) {
	doc, err := GenerateOpenAPI(root)
	if err != nil {
		return nil, nil, err
	}
	if current, err = contractLines(doc); err != nil {
		return nil, nil, err
	}
	data, err := os.ReadFile(filepath.Join(root, "docs", contractFile))
	if err != nil && !os.IsNotExist(err) {
		return nil, nil, err
	}
	for _, l := range strings.Split(string(data), "\n") {
		if l = strings.TrimSpace(l); l != "" && !strings.HasPrefix(l, "#") {
			recorded = append(recorded, l)
		}
	}
	return recorded, current, nil
}

const contractHeader = `# The v1 API contract: every endpoint, success status and response field apps may rely on.
# Generated by ` + "`go run ./tools/apidoc`" + `, which only adds lines. A test fails when the code no longer
# answers with a line here. Removing a line is a breaking change to /api/v1: only do it on purpose.
`

// WriteContract adds what the code answers with now to docs/api-v1-contract.txt, keeping every
// line already there.
func WriteContract(root string) error {
	recorded, current, err := contract(root)
	if err != nil {
		return err
	}
	all := slices.Compact(slices.Sorted(slices.Values(append(recorded, current...))))
	return os.WriteFile(filepath.Join(root, "docs", contractFile), []byte(contractHeader+strings.Join(all, "\n")+"\n"), 0o644)
}

// schemaKinds preserves nullable/alternative response types without erasing their child fields.
func schemaKinds(schema map[string]any, components map[string]map[string]any, seen []string) []string {
	if ref, ok := schema["$ref"].(string); ok {
		name := strings.TrimPrefix(ref, "#/components/schemas/")
		if slices.Contains(seen, name) || len(seen) > 6 {
			return []string{"any"}
		}
		if target, ok := components[name]; ok {
			return schemaKinds(target, components, append(seen, name))
		}
	}
	if list, ok := schema["anyOf"].([]any); ok {
		out := []string{}
		for _, alternative := range list {
			if sub, ok := alternative.(map[string]any); ok {
				for _, kind := range schemaKinds(sub, components, seen) {
					if !slices.Contains(out, kind) {
						out = append(out, kind)
					}
				}
			}
		}
		slices.Sort(out)
		return out
	}
	typ, _ := schema["type"].(string)
	return []string{cmpType(typ)}
}
